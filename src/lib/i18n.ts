import { useState, useEffect } from "react";

const LANG_KEY = "hospiq_lang";

export type Lang = "en" | "rw";

export function getLang(): Lang {
  if (typeof window === "undefined") return "en";
  return (localStorage.getItem(LANG_KEY) as Lang) ?? "en";
}

export function setLang(lang: Lang) {
  localStorage.setItem(LANG_KEY, lang);
  window.dispatchEvent(new Event("hospiq:lang"));
}

export function useLang() {
  const [lang, setLangState] = useState<Lang>(getLang);
  useEffect(() => {
    const handler = () => setLangState(getLang());
    window.addEventListener("hospiq:lang", handler);
    return () => window.removeEventListener("hospiq:lang", handler);
  }, []);
  return lang;
}

