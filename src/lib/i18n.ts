export type TKey = keyof typeof t.en;

function interpolate(value: string, values?: Record<string, string | number>) {
  if (!values) return value;
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function useT() {
  const lang = useLang();
  return (key: TKey, values?: Record<string, string | number>) => interpolate(t[lang][key] ?? t.en[key], values);
}
